#!/usr/bin/env node
/**
 * Seed bookings + guest slots into D1.
 *
 * Usage:
 *   node scripts/seed-bookings.js scripts/seed-data.json [--dry-run]
 *
 * Output: SQL statements that can be piped to wrangler:
 *   node scripts/seed-bookings.js scripts/seed-data.json --dry-run
 *   node scripts/seed-bookings.js scripts/seed-data.json > seed-output.sql
 *   npx wrangler d1 execute swa-portal --remote --file=seed-output.sql
 *
 * The script is idempotent: it skips bookings that already exist (by booking_ref).
 * Guest slots are allocated sequentially within each table.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const dataFile = args.find(a => !a.startsWith('--'));

if (!dataFile) {
  console.error('Usage: node scripts/seed-bookings.js <seed-data.json> [--dry-run]');
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(dataFile, 'utf-8'));

// Table config must match KV config (swa:reg_tables_config)
const TABLES = [
  { id: '01', label: 'Table 1', ticketPrefix: '01', capacity: 10, isVIP: false },
  { id: '02', label: 'Table 2', ticketPrefix: '02', capacity: 10, isVIP: false },
  { id: 'VIP-1', label: 'VIP-1', ticketPrefix: 'V1', capacity: 10, isVIP: true },
  { id: 'VIP-2', label: 'VIP-2', ticketPrefix: 'V2', capacity: 10, isVIP: true },
];

function getTable(tableId) {
  return TABLES.find(t => t.id === tableId);
}

function sqlEscape(str) {
  if (str === null || str === undefined) return 'NULL';
  return "'" + String(str).replace(/'/g, "''") + "'";
}

const statements = [];

for (const booking of data.bookings) {
  const table = getTable(booking.table_id);
  if (!table) {
    console.error(`ERROR: Table "${booking.table_id}" not found in config. Available: ${TABLES.map(t => t.id).join(', ')}`);
    process.exit(1);
  }

  const id = crypto.randomUUID();
  const pax = booking.pax || 1;

  // Booking INSERT
  statements.push(`-- Booking: ${booking.buyer_name} (${booking.booking_ref}) at ${table.label}, ${pax} pax`);
  statements.push(
    `INSERT INTO reg_bookings (id, booking_ref, buyer_name, buyer_email, buyer_phone, table_id, pax, notes, created_by) ` +
    `VALUES (${sqlEscape(id)}, ${sqlEscape(booking.booking_ref)}, ${sqlEscape(booking.buyer_name)}, ${sqlEscape(booking.buyer_email)}, ${sqlEscape(booking.buyer_phone)}, ${sqlEscape(booking.table_id)}, ${pax}, ${sqlEscape(booking.notes)}, ${sqlEscape('seed-script')});`
  );

  // Guest slot INSERTs
  const overrides = (data.guest_overrides || []).filter(g => g.booking_ref === booking.booking_ref);

  for (let i = 1; i <= pax; i++) {
    const isBuyer = i === 1;
    const seatCounter = i;
    const ticketCode = `${table.ticketPrefix}-${String(seatCounter).padStart(2, '0')}`;
    const guestId = crypto.randomUUID();

    const override = overrides.find(g => g.seat === i);
    const guestName = override ? override.guest_name : (isBuyer ? booking.buyer_name : null);
    const notes = override ? (override.notes || null) : null;

    statements.push(
      `INSERT INTO reg_guests (id, booking_id, table_id, seat_counter, ticket_code, guest_name, is_buyer, is_walk_in, notes) ` +
      `VALUES (${sqlEscape(guestId)}, ${sqlEscape(id)}, ${sqlEscape(booking.table_id)}, ${seatCounter}, ${sqlEscape(ticketCode)}, ${sqlEscape(guestName)}, ${isBuyer ? 1 : 0}, 0, ${sqlEscape(notes)});`
    );
  }

  statements.push(''); // blank line between bookings
}

console.log('-- Seed data generated by scripts/seed-bookings.js');
console.log(`-- Bookings: ${data.bookings.length}, Total guest slots: ${data.bookings.reduce((sum, b) => sum + (b.pax || 1), 0)}`);
console.log(`-- Generated at: ${new Date().toISOString()}`);
if (dryRun) {
  console.log('-- DRY RUN: no data was written');
}
console.log('');

for (const stmt of statements) {
  console.log(stmt);
}

if (!dryRun && statements.length > 0) {
  console.error('');
  console.error('To apply this to production D1, save the output and run:');
  console.error('  npx wrangler d1 execute swa-portal --remote --file=seed-output.sql');
} else if (dryRun) {
  console.error('\n-- This was a dry run. Remove --dry-run to generate real SQL.');
}