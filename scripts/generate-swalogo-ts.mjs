#!/usr/bin/env node
// Generates src/worker/lib/swalogo-generated.ts from public/swa-logo.webp.
//
// Why this exists:
//   The server-rendered namecard card SVG (/c/:slug/card.svg) needs the SWA
//   logo INLINED as a data URI — an external `<img src="/swa-logo.webp">`
//   inside the SVG would taint the canvas when the SVG is later rasterised
//   to PNG client-side (docs/specs/features/namecards.md §8.2). This script bakes the WebP
//   bytes into a base64 data URI constant the worker can import.
//
//   The client-side QR overlay does NOT need this — it loads the WebP
//   directly via `new Image(); logo.src = '/swa-logo.webp'` (same-origin, no
//   taint), mirroring the proven PayNow QR pattern in
//   src/pages/reg/membership/register.astro.
//
//   We use the WebP (not public/swalogo.svg) because some browsers
//   mis-rasterise transparent SVG corners as black when drawn to canvas;
//   the WebP decodes reliably with proper alpha everywhere. The PayNow QR
//   has shipped this asset without issue.
//
// Regenerate after replacing public/swa-logo.webp by running:
//   npm run gen:swalogo
//
// The predev and prebuild hooks run this automatically.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SRC = join(ROOT, 'public', 'swa-logo.webp');
const OUT = join(ROOT, 'src', 'worker', 'lib', 'swalogo-generated.ts');

const buf = readFileSync(SRC);
const b64 = buf.toString('base64');
const dataUri = `data:image/webp;base64,${b64}`;

const ts = `// AUTO-GENERATED by scripts/generate-swalogo-ts.mjs.
// Do not edit by hand — replace public/swa-logo.webp and run \`npm run gen:swalogo\`.
//
// The SWA logo as a base64 data URI, for embedding inside the server-rendered
// namecard card SVG (/c/:slug/card.svg). The card SVG must be self-contained
// (no external resource references) so the client-side canvas PNG export is
// not tainted by a cross-origin load (docs/specs/features/namecards.md §8.2).
//
// Source asset: public/swa-logo.webp — the SAME logo used by the admin nav
// (src/layouts/AdminLayout.astro:64) and the PayNow QR overlay
// (src/pages/reg/membership/register.astro:187). One asset, three uses.

/* eslint-disable */

export const SWA_LOGO_DATA_URI: string = ${JSON.stringify(dataUri)};
`;

writeFileSync(OUT, ts);
console.log(`Generated ${OUT} (${buf.length} bytes of source WebP).`);
